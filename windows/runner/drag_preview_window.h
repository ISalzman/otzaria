#ifndef RUNNER_DRAG_PREVIEW_WINDOW_H_
#define RUNNER_DRAG_PREVIEW_WINDOW_H_

#include <windows.h>

#include <string>

// תצוגת הכרטיסיה הנגררת **מחוץ** לחלון.
//
// ⚠️ למה נייטיב ולא Flutter. ה-`feedback` של `Draggable` מצויר בתוך
// ה-Overlay של החלון, ולכן הוא נחתך בגבולותיו: ברגע שהסמן יוצא, הכרטיסיה
// פשוט נעלמת. המשתמש לא רואה שהוא גורר משהו, ולכן גם אינו יכול לכוון
// לשורת המשימות או לחלון אחר.
//
// זהו חלון layered, topmost ו-transparent-to-hit-test שעוקב אחרי הסמן.
// `WS_EX_TRANSPARENT` הוא קריטי: בלעדיו החלון עצמו היה נמצא תחת הסמן,
// ו-`WindowFromPoint` היה מחזיר אותו במקום את היעד האמיתי.
namespace drag_preview {

// ממיר UTF-8 ל-UTF-16. ה-runner ממיר רק בכיוון ההפוך (`Utf8FromUtf16`),
// והכותרת מגיעה מ-Dart כ-UTF-8.
std::wstring Utf16FromUtf8(const std::string& utf8);

// צבעי הערכה, שמגיעים מ-Dart.
//
// ⚠️ הם היו מקודדים קשיח בגוונים בהירים. בערכה כהה זה נראה כמו מלבן לבן
// זוהר על מסך כהה — הפוך בדיוק ממה שהמשתמש מצפה שייגרר. הצבעים מגיעים
// מ-`colorScheme`, כמו כל צבע אחר בתוכנה.
struct Colors {
  bool valid = false;
  COLORREF strip = 0;
  COLORREF tab = 0;
  COLORREF body = 0;
  COLORREF border = 0;
  COLORREF text = 0;
};

// מתחיל להציג תצוגת גרירה עם הכותרת הנתונה.
//
// התצוגה מוסתרת כשהסמן מעל **חלון המקור** [source] — שם ה-`feedback` של
// Flutter כבר עושה את העבודה, ושתי תצוגות במקביל היו נראות כשכפול.
//
// ⚠️ **המקור בלבד, ולא "כל חלון של התהליך".** הגרסה הראשונה הסתירה מעל
// כל חלון אוצריא, וזה יצר חור: ה-`feedback` של Flutter מצויר ב-Overlay
// של חלון המקור ונחתך בגבולותיו, ולכן מעל חלון אוצריא **אחר** לא נראתה
// לא התצוגה הנייטיבית ולא ה-feedback — הכרטיסיה הנגררת פשוט נעלמה, ונשאר
// רק קו ההכנסה הדק. זה בדיוק הרגע שבו המשתמש צריך לראות מה הוא מזיז.
void Begin(const std::wstring& title, HWND source, const Colors& colors);

// מחליף את הכרטיסיה המשורטטת בתמונה **אמיתית** שלה, כפי שהיא נראית בחלון
// המקור.
//
// ⚠️ שרטוט מחדש ב-GDI לא יכול להיות זהה: הוא לא יודע את הגופן, את אייקון
// סוג הכרטיסיה, את כפתור ה-X, את סימון הבחירה או את ההצללה. המשתמש ביקש
// שהגרירה תיראה כמו בכרום — כלומר הכרטיסיה עצמה — ולכן Dart מצלם את
// ה-`RepaintBoundary` של הכרטיסיה ושולח את הפיקסלים.
//
// [rgba] הוא RGBA **מוכפל-מראש** (זה מה ש-`rawRgba` של Flutter מחזיר), ו-
// [dpr] הוא ה-devicePixelRatio שבו צולם — כדי שהתמונה תצויר בגודל הלוגי
// הנכון ולא כפול.
//
// הקריאה אופציונלית: התצוגה מופיעה מיד עם שרטוט GDI, והתמונה מחליפה אותו
// פריים אחר כך. כך אין רגע שבו לא נראה כלום.
void SetImage(const unsigned char* rgba, int width, int height, double dpr);

// עוצר את המעקב אחרי הסמן ומשאיר את התצוגה **גלויה במקום השחרור**.
//
// ⚠️ מכסה את הפער שבין השחרור לבין הופעת החלון האמיתי — מאות מילישניות
// שבהן המסך היה ריק והמשתמש לא ידע אם משהו קורה. הרוח נשארת במקום שגררו
// אליו, והחלון האמיתי מחליף אותה. יש רשת ביטחון של ארבע שניות, כדי
// שיצירה שנכשלה בשקט לא תשאיר אותה תלויה.
void Freeze();

// מסיים את הגרירה ומסתיר את התצוגה.
void End();

// האם תצוגת גרירה פעילה כרגע.
bool IsActive();

}  // namespace drag_preview

#endif  // RUNNER_DRAG_PREVIEW_WINDOW_H_
