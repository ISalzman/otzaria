#ifndef RUNNER_DRAG_PREVIEW_WINDOW_H_
#define RUNNER_DRAG_PREVIEW_WINDOW_H_

#include <windows.h>

#include <string>

// הכרטיסיה הנגררת **מחוץ** לחלון.
//
// ⚠️ למה נייטיב ולא Flutter. ה-`feedback` של `Draggable` מצויר בתוך
// ה-Overlay של החלון, ולכן הוא נחתך בגבולותיו: ברגע שהסמן יוצא, הכרטיסיה
// פשוט נעלמת. המשתמש לא רואה שהוא גורר משהו, ולכן גם אינו יכול לכוון
// לשורת המשימות או לחלון אחר.
//
// ## שני דברים שהחלון הזה **אינו**
//
// הוא אינו תווית ואינו מוק של חלון. גרסה קודמת ציירה "חלון מוקטן"
// 300×196 — רצועה, כרטיסיה וגוף — והמשתמש תיאר את התוצאה כקופסה חיוורת
// שרואים דרכה את מה שמאחור. זה היה נכון: הגוף היה ריק כי אין לנו מה
// לצייר בו, ושרטוט GDI של כרטיסיה אינו יכול להיות זהה למקור (גופן,
// אייקון סוג, כפתור X, סימון בחירה, הצללה).
//
// לכן מה שנגרר הוא **צילום הכרטיסיה עצמה**, בגודלה הפיזי המדויק, עם ערוץ
// אלפא לכל פיקסל — כלומר הפינות המעוגלות שקופות באמת. הוא נראה כמו
// הכרטיסיה כי הוא הכרטיסיה.
//
// ## והוא חלון שהמערכת מוכנה לגרור
//
// אין ב-Win32 API שפותח את Snap Layouts. ה-shell פותח אותו בעצמו, ורק
// כשהוא משוכנע שנגרר **חלון** — ולכן זה חלון עם סגנונות של חלון אמיתי
// (`WS_OVERLAPPEDWINDOW`), שהמסגרת שלו מבוטלת ב-`WM_NCCALCSIZE`. ראו
// [DragWithSystem].
namespace drag_preview {

// ממיר UTF-8 ל-UTF-16. ה-runner ממיר רק בכיוון ההפוך (`Utf8FromUtf16`),
// והכותרת מגיעה מ-Dart כ-UTF-8.
std::wstring Utf16FromUtf8(const std::string& utf8);

// צבעי הערכה, שמגיעים מ-Dart.
//
// ⚠️ הם היו מקודדים קשיח בגוונים בהירים. בערכה כהה זה נראה כמו מלבן לבן
// זוהר על מסך כהה — הפוך בדיוק ממה שהמשתמש מצפה שייגרר. הצבעים מגיעים
// מ-`colorScheme`, כמו כל צבע אחר בתוכנה.
//
// בפועל הם משמשים רק לרגע שלפני שהצילום מגיע. משם והלאה הפיקסלים הם של
// הכרטיסיה האמיתית, ואין מה לצבוע.
/// ⚠️ שלושה צבעים ולא חמישה. הגרסה שציירה "חלון מוקטן" צבעה גם רצועה
/// וגם גוף; מאז מה שנגרר הוא צילום, והשרטוט שקודם לו הוא כרטיסיה בלבד.
/// צבעים שאיש אינו מצייר בהם רק מזמינים את המתחזק לחפש היכן הם משמשים.
struct Colors {
  bool valid = false;
  COLORREF tab = 0;
  COLORREF border = 0;
  COLORREF text = 0;
};

// מתחיל להציג את הכרטיסיה הנגררת.
//
// התצוגה מוסתרת כשהסמן מעל **חלון המקור** [source] — שם ה-`feedback` של
// Flutter כבר עושה את העבודה, ושתי כרטיסיות במקביל היו נראות כשכפול.
//
// ⚠️ **המקור בלבד, ולא "כל חלון של התהליך".** הגרסה הראשונה הסתירה מעל
// כל חלון אוצריא, וזה יצר חור: ה-`feedback` של Flutter מצויר ב-Overlay
// של חלון המקור ונחתך בגבולותיו, ולכן מעל חלון אוצריא **אחר** לא נראתה
// לא התצוגה הנייטיבית ולא ה-feedback — הכרטיסיה הנגררת פשוט נעלמה, ונשאר
// רק קו ההכנסה הדק. זה בדיוק הרגע שבו המשתמש צריך לראות מה הוא מזיז.
void Begin(const std::wstring& title, HWND source, const Colors& colors);

// מחליף את השרטוט בצילום, ומתאים את גודל החלון ל-[target_width] ×
// [target_height].
//
// [rgba] הוא RGBA **מוכפל-מראש** — זה מה ש-`rawRgba` של Flutter מחזיר.
//
// ⚠️ **גודל היעד נפרד מגודל הצילום, ובמכוון.** מה שנגרר הוא מוק של החלון
// שייפתח — כרטיסיה **והתוכן שלה** — כלומר בגודל חלון מלא. צילום כזה
// בפיקסלים פיזיים הוא כמה מיליוני פיקסלים, והעברתו בערוץ בתחילת כל
// גרירה היא עשרות MB. לכן Dart מצלם קטן יותר ומוסר את הגודל שבו התצוגה
// צריכה להופיע, וה-GDI מותח. תמונת רפאים סובלת מתיחה; המשתמש לא סובל
// השהיה בתחילת גרירה.
//
// הקריאה אופציונלית: התצוגה מופיעה מיד עם שרטוט, והצילום מחליף אותו
// פריים אחר כך. כך אין רגע שבו לא נראה כלום.
// [rgba_size] הוא אורך המאגר בבתים. נדרש כי המידות מגיעות מ-Dart בנפרד
// ממנו, וקריאה של `width*height*4` בלי לאמת אותן קראה מעבר לסופו.
void SetImage(const unsigned char* rgba, size_t rgba_size, int width,
              int height, int target_width, int target_height);

// עוצר את המעקב אחרי הסמן ומשאיר את התצוגה **גלויה במקום השחרור**.
//
// ⚠️ מכסה את הפער שבין השחרור לבין הופעת החלון האמיתי — מאות מילישניות
// שבהן המסך היה ריק והמשתמש לא ידע אם משהו קורה. הרוח נשארת במקום שגררו
// אליו, והחלון האמיתי מחליף אותה. יש רשת ביטחון של ארבע שניות, כדי
// שיצירה שנכשלה בשקט לא תשאיר אותה תלויה.
void Freeze();

// מסיים את הגרירה ומסתיר את התצוגה.
void End();


// מה נמצא תחת [pt], **בהתעלמות מהתצוגה עצמה**.
//
// ⚠️ נדרש כי התצוגה אינה `WS_EX_TRANSPARENT` יותר. הדגל הזה הוציא אותה
// מחישוב ה-hit-test בחינם, אבל חלון שאינו נמצא תחת הסמן אינו נראה
// ל-shell כחלון שנגרר — ובלי זה אין Snap Layouts. במקומו הדגל מודלק
// לרגע החישוב בלבד, וזו הפעולה היחידה שצריכה לדעת על התצוגה.
HWND WindowUnderCursor(POINT pt);

// תוצאת גרירה שנוהלה בידי Windows.
struct SystemDragResult {
  // האם לולאת ההזזה בכלל רצה. false כשהכפתור שוחרר לפני שהתחלנו.
  bool ran = false;
  // המסגרת הסופית בקואורדינטות מסך — **אחרי** הצמדה, אם המשתמש הצמיד.
  RECT rect{};
  // האם Windows שינה את גודל התצוגה, כלומר המשתמש הצמיד אותה.
  //
  // ⚠️ ההבחנה קריטית. התצוגה היא בגודל **כרטיסיה**, ולכן שימוש עיוור
  // ב-[rect] כמסגרת החלון החדש היה יוצר חלון אוצריא של 176×40. כשלא
  // הוצמד — רק הפינה רלוונטית, והגודל נורש מחלון המקור.
  bool snapped = false;
  POINT cursor{};
  // מה שתחת הסמן בשחרור, בהתעלמות מהתצוגה.
  HWND under = nullptr;
};

// מוסר ל-Windows את המשך הגרירה של התצוגה, וחוסם עד שהמשתמש שחרר.
//
// ## למה זו הדרך היחידה ל-Snap Layouts
//
// אין API שפותח את התפריט. ה-shell פותח אותו בעצמו, ורק כשהמשתמש גורר
// חלון לעבר קצה המסך. כל עוד הכרטיסיה נגררת בתוך התהליך שלנו — Flutter
// לוכד את הסמן, אנחנו מזיזים חלון layered בטיימר — מבחינת Windows שום
// חלון אינו נגרר.
//
// `ReleaseCapture()` + `WM_NCLBUTTONDOWN`/`HTCAPTION` מכניסים אותנו
// ללולאת ההזזה המודאלית של Windows: אותה לולאה בדיוק שרצה כשגוררים חלון
// מהכותרת שלו. מכאן המשתמש מקבל את כל התנהגות ההצמדה של המערכת — Snap
// Layouts, Aero Snap, מסכים, והגדרות שהוא בחר — ולא חיקוי חלקי שלה.
//
// ⚠️ **הלולאה חוסמת את ה-platform thread**, וכל המנועים חולקים אותו
// (ראו docs/multi-window.md) — שאר החלונות קופאים למשך הגרירה. זו
// בדיוק ההתנהגות הקיימת: גרירת חלון אוצריא מהכותרת שלו עושה את אותו
// דבר גם היום.
//
// ⚠️ **התצוגה נשארת גלויה במקום שבו שוחררה.** מי שקורא אחראי להסתיר
// (`End`) או להחליף אותה בחלון אמיתי — אחרת היא נשארת תלויה.
SystemDragResult DragWithSystem();

}  // namespace drag_preview

#endif  // RUNNER_DRAG_PREVIEW_WINDOW_H_
