// Enums להגדרות האפליקציה

/// מצב הצגת ניקוד
enum NikudDisplayMode {
  /// הצג ניקוד בכל הספרים
  showAll,

  /// הצג ניקוד רק בספרי התנ"ך
  showTanachOnly,

  /// אל תציג ניקוד בשום ספר
  hideAll,
}

/// מצב סרגל הצד
enum SidebarMode {
  /// סרגל הצד סגור תמיד
  hidden,

  /// סרגל הצד נפתח בפתיחת ספר ונסגר בגלילה
  open,

  /// סרגל הצד מוצמד ונשאר פתוח תמיד
  pinned,
}
